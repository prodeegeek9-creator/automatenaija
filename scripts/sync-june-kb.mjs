// Copies June's built-in answers from the dashboard app into assets/june.js,
// so the June on this site and the June inside the app say the same things.
//
//   node scripts/sync-june-kb.mjs ../automate-naija-app/src/lib/juneKb.js
//
// The app's src/lib/juneKb.js is the source of truth. This script reads its
// JUNE_KB, puts the visitor-only answers below in front (they win a tie, so
// "how do I join" is about signing up, not about submitting a build), and
// rewrites the block between the JUNE_KB markers in assets/june.js. Run it
// whenever the app's answers change, then commit assets/june.js.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/sync-june-kb.mjs <path to automate-naija-app/src/lib/juneKb.js>');
  process.exit(1);
}

const { JUNE_KB } = await import(pathToFileURL(resolve(source)).href);
if (!Array.isArray(JUNE_KB) || !JUNE_KB.length) throw new Error('No JUNE_KB array in ' + source);

// Answers only a visitor needs. Kept here because the app has no use for them.
const SITE_ONLY = [
  {
    id: 'signup',
    k: ['sign up', 'signup', 'register', 'registration', 'create account', 'create an account', 'open an account',
      'join', 'how do i join', 'how can i join', 'log in', 'login', 'start free', 'get started', 'how do i start',
      'where do i start', 'account'],
    a: "Create your free account at https://app.automatenaija.com/login, no card needed. Then:\n1. Add a clear photo of your face on /profile.\n2. Open this week's builds at /challenges. Your first build is free and never closes, and every Beginner build is free.\n\nWant to learn from zero first? After signing up, open /learn to see the whole course outline before you pay.",
  },
  {
    id: 'whatsapp-join',
    k: ['whatsapp group', 'whatsapp community', 'join whatsapp', 'whatsapp link', 'telegram', 'discord', 'group chat'],
    a: 'The Automate Naija WhatsApp community is free: builders post errors, share wins and find people to build with. The join button is in the Community section of this page. Inside the app, /community is the forum.',
  },
];

const siteIds = new Set(SITE_ONLY.map((e) => e.id));
const kb = [...SITE_ONLY, ...JUNE_KB.filter((e) => !siteIds.has(e.id))].map((e) => {
  const out = { id: e.id, k: e.k, a: e.a };
  if (e.short) out.short = true;
  return out;
});

const target = new URL('../assets/june.js', import.meta.url);
const js = readFileSync(target, 'utf8');
const START = '/* JUNE_KB:START (generated by scripts/sync-june-kb.mjs, do not edit by hand) */';
const END = '/* JUNE_KB:END */';
const from = js.indexOf(START);
const to = js.indexOf(END);
if (from < 0 || to < from) throw new Error('JUNE_KB markers not found in assets/june.js');

const block = START + '\n  var JUNE_KB = ' + JSON.stringify(kb, null, 2).replace(/\n/g, '\n  ') + ';\n  ';
writeFileSync(target, js.slice(0, from) + block + js.slice(to));
console.log('assets/june.js: ' + kb.length + ' answers (' + SITE_ONLY.length + ' site-only, ' + JUNE_KB.length + ' from the app)');
